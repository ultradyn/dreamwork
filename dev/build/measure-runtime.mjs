#!/usr/bin/env node
/* Measure the P2 runtime independently of migrated route components.
 *
 * The production bundle deliberately grows as routes migrate to React.  This
 * entry rebuilds the stable subject that the page-weight guard originally
 * meant: React + ReactDOM + the registry + one coexistence probe.  It is a
 * measurement build only; it does not change client/dist/native.js.
 */
import path from 'node:path';
import process from 'node:process';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const rootAt = process.argv.indexOf('--root');
const toolRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const root = path.resolve(rootAt >= 0 ? process.argv[rootAt + 1] : toolRoot);
if (rootAt >= 0 && !process.argv[rootAt + 1]) {
  throw new Error('--root needs a path');
}

// This is the original P2 shape, expressed as a synthetic entry so later
// registrations in native-entry.js cannot leak ordinary UI work into it.
const entry = String.raw`
import React from 'react';
import * as ReactDOM from 'react-dom/client';
import { createRegistry, OWNED_ATTR } from './registry.js';
import { registerProbe, PROBE_ROUTE } from './probe.js';
const registry = createRegistry();
registerProbe(registry);
export { React, ReactDOM, registry, PROBE_ROUTE, OWNED_ATTR };
export const version = React.version;
`;

const commonDir = execFileSync(
  'git', ['rev-parse', '--path-format=absolute', '--git-common-dir'],
  { cwd: toolRoot, encoding: 'utf8' }).trim();
const candidates = [
  path.join(toolRoot, 'dev', 'build', 'node_modules'),
  path.join(path.dirname(commonDir), 'dev', 'build', 'node_modules'),
];
const nodeModules = candidates.find(candidate =>
  fs.existsSync(path.join(candidate, 'esbuild', 'package.json')));
if (!nodeModules) {
  throw new Error('esbuild is absent; run `just build-client` first');
}
const require = createRequire(import.meta.url);
const { build } = require(path.join(nodeModules, 'esbuild'));
const result = await build({
  stdin: {
    contents: entry,
    resolveDir: path.join(root, 'dev', 'build', 'src'),
    sourcefile: 'runtime-budget-entry.js',
  },
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'dwNative',
  target: 'es2020',
  charset: 'utf8',
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: true,
  lineLimit: 200,
  nodePaths: [nodeModules],
  banner: { js: `/* GENERATED by \`just build-client\` (dev/build_client.py) — DO NOT EDIT.
 *
 * Built from client/*.js in watch.py's own _CLIENT_ASSETS order, plus
 * dev/build/wrapper-exports.js. Edit those; then rebuild. If you edit an
 * input without rebuilding, \`python3 lint.py\` goes ERROR and names the file:
 * client/dist/manifest.json records the sha256 of every input and output.
 */` },
  plugins: [{
    name: 'exclude-migrated-probe-child',
    setup(build) {
      build.onResolve({ filter: /^\.\/research\.js$/ }, args =>
        args.importer.endsWith('/probe.js') ?
          { path: args.path, namespace: 'component-stub' } : null);
      build.onLoad({ filter: /.*/, namespace: 'component-stub' }, () => ({
        contents: 'export const Research = () => null;',
        loader: 'js',
      }));
    },
  }],
});
if (result.outputFiles.length !== 1 || !result.outputFiles[0].contents.length) {
  throw new Error('runtime measurement emitted no single non-empty bundle');
}
process.stdout.write(JSON.stringify({
  runtime_bytes: result.outputFiles[0].contents.length,
}) + '\n');
