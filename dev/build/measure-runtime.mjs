#!/usr/bin/env node
/* Measure the P2 runtime independently of migrated route components.
 *
 * The production bundle deliberately grows as routes migrate to React.  This
 * entry rebuilds the stable subject that the page-weight guard originally
 * meant: React + ReactDOM + the registry + one coexistence probe.  It is a
 * measurement build only; it does not change client/dist/native.js.
 */
import path from 'node:path';
import process from 'node:process';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const rootAt = process.argv.indexOf('--root');
const toolRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const root = path.resolve(rootAt >= 0 ? process.argv[rootAt + 1] : toolRoot);
if (rootAt >= 0 && !process.argv[rootAt + 1]) {
  throw new Error('--root needs a path');
}

// This is the original P2 shape, expressed as a synthetic entry so later
// registrations in native-entry.js cannot leak ordinary UI work into it.
const entry = String.raw`
import React from 'react';
import * as ReactDOM from 'react-dom/client';
import { createRegistry, OWNED_ATTR } from './registry.js';
import { fromBuilder } from './delegate.js';

const ResearchListing = fromBuilder('buildResearch', props =>
  buildResearch(null, props.data || null));

function Probe(props) {
  const [instance] = React.useState(() =>
    'p' + Math.random().toString(36).slice(2, 10));
  const [seen, setSeen] = React.useState(0);
  React.useEffect(() => setSeen(n => n + 1), [props.data]);
  return React.createElement('div', { 'data-dw-probe': 'research' },
    React.createElement('span', {
      'data-dw-probe-instance': instance,
      'data-dw-probe-seen': String(seen),
    }),
    React.createElement(ResearchListing, { data: props.data }));
}

const PROBE_ROUTE = '__probe';
const registry = createRegistry();
registry.register(PROBE_ROUTE, { component: Probe });
export { React, ReactDOM, registry, PROBE_ROUTE, OWNED_ATTR };
export const version = React.version;
`;

const commonDir = execFileSync(
  'git', ['rev-parse', '--path-format=absolute', '--git-common-dir'],
  { cwd: toolRoot, encoding: 'utf8' }).trim();
const candidates = [
  path.join(toolRoot, 'dev', 'build', 'node_modules', '.bin', 'esbuild'),
  path.join(path.dirname(commonDir), 'dev', 'build', 'node_modules', '.bin',
    'esbuild'),
];
const esbuild = candidates.find(candidate => {
  try { return execFileSync('test', ['-x', candidate]).length === 0; }
  catch { return false; }
});
if (!esbuild) {
  throw new Error('esbuild is absent; run `just build-client` first');
}
const result = spawnSync(esbuild, [
  '--bundle', '--format=iife', '--global-name=dwNative', '--target=es2020',
  '--charset=utf8', '--define:process.env.NODE_ENV="production"', '--minify',
  '--line-limit=200', '--loader=js',
  '--banner:js=/* GENERATED by `just build-client` (dev/build_client.py) — DO NOT EDIT.\n *\n * Built from client/*.js in watch.py\'s own _CLIENT_ASSETS order, plus\n * dev/build/wrapper-exports.js. Edit those; then rebuild. If you edit an\n * input without rebuilding, `python3 lint.py` goes ERROR and names the file:\n * client/dist/manifest.json records the sha256 of every input and output.\n */',
], {
  cwd: path.join(root, 'dev', 'build', 'src'),
  env: { ...process.env,
    NODE_PATH: path.resolve(path.dirname(esbuild), '..') },
  input: entry,
  maxBuffer: 4 * 1024 * 1024,
});
if (result.status !== 0) {
  throw new Error('esbuild failed: ' + result.stderr.toString().trim());
}

if (result.stdout.length === 0) throw new Error('runtime measurement is empty');
process.stdout.write(JSON.stringify({
  runtime_bytes: result.stdout.length,
}) + '\n');
